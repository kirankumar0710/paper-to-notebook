"""Panel 5 (Download): notebooks generated since the server started.

``GET /api/notebooks`` lists them and ``GET /api/notebooks/{id}`` downloads
one. Only notebooks this server saved are served, by a random id, so these
endpoints never expose other files in the output folder.
"""

from __future__ import annotations

import time
import uuid
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from fastapi import APIRouter, HTTPException, status
from fastapi.responses import FileResponse

from api.settings import IPYNB_MEDIA_TYPE
from util.files import save_unique
from util.log import get_logger

__all__ = ["MAX_LISTED_NOTEBOOKS", "SavedNotebook", "router", "save_notebook"]

MAX_LISTED_NOTEBOOKS = 20

logger = get_logger(__name__)
router = APIRouter()


@dataclass(frozen=True)
class SavedNotebook:
    """A notebook this server generated and saved in the output folder."""

    id: str
    filename: str
    path: Path
    title: str
    created: float  # Unix time

    @property
    def download_url(self) -> str:
        return f"/api/notebooks/{self.id}"

    def to_dict(self) -> dict[str, Any]:
        exists = self.path.is_file()
        return {
            "id": self.id,
            "filename": self.filename,
            "path": str(self.path),
            "title": self.title,
            "created": self.created,
            "size": self.path.stat().st_size if exists else None,
            "exists": exists,
            "download_url": self.download_url,
        }


# Notebooks saved since the server started, newest last.
_saved_notebooks: dict[str, SavedNotebook] = {}


def save_notebook(
    directory: Path, filename: str, title: str, notebook_json: str
) -> SavedNotebook | None:
    """Save the notebook on the server and remember it for this panel.

    The copy means the notebook is not lost if the browser does not save
    the download. A failure here never fails the request.
    """
    try:
        path = save_unique(directory, filename, notebook_json)
    except OSError as exc:
        logger.warning("Could not save a copy of %r: %s", filename, exc)
        return None
    logger.info("Saved a copy to %s", path)
    saved = SavedNotebook(
        id=uuid.uuid4().hex,
        filename=path.name,
        path=path,
        title=title,
        created=time.time(),
    )
    _saved_notebooks[saved.id] = saved
    return saved


@router.get("/api/notebooks")
async def list_notebooks() -> list[dict[str, Any]]:
    """Notebooks generated since the server started, newest first."""
    recent = list(_saved_notebooks.values())[-MAX_LISTED_NOTEBOOKS:]
    return [saved.to_dict() for saved in reversed(recent)]


@router.get("/api/notebooks/{notebook_id}")
async def download_notebook(notebook_id: str) -> FileResponse:
    """Download a notebook generated by this server."""
    saved = _saved_notebooks.get(notebook_id)
    if saved is None or not saved.path.is_file():
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Notebook not found. It may have been moved or deleted.",
        )
    return FileResponse(
        saved.path, media_type=IPYNB_MEDIA_TYPE, filename=saved.filename
    )
